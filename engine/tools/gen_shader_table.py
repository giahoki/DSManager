r"""Builds src/game_shaders.h: DXBC checksum -> name for the game's post/menu/deferred/sfx shaders and scene vertex shaders.

Usage: python gen_shader_table.py "<DARK SOULS REMASTERED>\shader" ..\src\game_shaders.h

Only checksums and file names go into the header (no game bytecode). The engine uses them to
recognise which pass the game is drawing (tonemap, bloom, menu...).
"""
import sys
from pathlib import Path

from soulstruct.containers import Binder

BUNDLES = ("FRPG_Filter_DX11", "FRPG_Menu_DX11", "FRPG_Deferred_DX11", "FRPG_SfxPBL_DX11", "FRPG_FlverPBL_vpo_DX11")

rows = []
for bnd in BUNDLES:
    for e in Binder.from_path(Path(sys.argv[1]) / f"{bnd}.shaderbnd.dcx").entries:
        data = bytes(e.data)
        if data[:4] != b"DXBC":
            continue
        a, b, c, d = (int.from_bytes(data[4 + 4 * i:8 + 4 * i], "little") for i in range(4))
        rows.append(f'    {{{{0x{a:08x}u, 0x{b:08x}u, 0x{c:08x}u, 0x{d:08x}u}}, "{e.name}"}},')

Path(sys.argv[2]).write_text(
    "// Generated by tools/gen_shader_table.py from the game's shader\\*.shaderbnd.dcx. Do not edit.\n"
    "#pragma once\n#include <cstdint>\n\n"
    "struct GameShader { uint32_t sum[4]; const char* name; };\n\n"
    "inline constexpr GameShader kGameShaders[] = {\n" + "\n".join(rows) + "\n};\n",
    encoding="utf-8")
print(len(rows), "shaders")
